def tr(text: str, language: str = "es") -> str:
    """Translate known Spanish UI strings; unknown (e.g. API) text is preserved."""
    if language != "en":
        return text
    if text.startswith("Máximo ") and text.endswith(" caracteres por pregunta."):
        return text.replace("Máximo ", "Maximum ").replace(" caracteres por pregunta.", " characters per question.")
    return TRANSLATIONS.get(text, text)


def focus_reason(reason: str, spanish_text: str, language: str = "es") -> str:
    if language != "en":
        return spanish_text
    return ENGLISH_FOCUS_REASONS.get(reason, spanish_text)
